package installer

import (
	"fmt"
	"os"
	"path/filepath"
	"regexp"
	"strings"

	"github.com/wonskur/upm/internal/utils"
)

var safeComponent = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._+-]*$`)

// GenerateBwrapWrapper creates an executable wrapper script content
// that invokes the foreign binary inside an isolated bubblewrap environment.
func GenerateBwrapWrapper(provider, pkgName, binaryName, targetBinPath string) (string, error) {
	if provider == "" || pkgName == "" || binaryName == "" || targetBinPath == "" {
		return "", fmt.Errorf("invalid arguments: provider, pkgName, binaryName and targetBinPath must not be empty")
	}
	for label, value := range map[string]string{"provider": provider, "package name": pkgName, "binary name": binaryName} {
		if !safeComponent.MatchString(value) || value == "." || value == ".." {
			return "", fmt.Errorf("invalid %s %q", label, value)
		}
	}

	optDir := filepath.Join(utils.RuntimeOptDir(), provider, pkgName)
	if !filepath.IsAbs(targetBinPath) || filepath.Clean(targetBinPath) != targetBinPath || strings.ContainsAny(targetBinPath, "\r\n\x00") {
		return "", fmt.Errorf("invalid target binary path %q", targetBinPath)
	}
	allowedDirs := map[string]bool{"/usr/bin": true, "/bin": true, "/usr/sbin": true, "/sbin": true}
	if !allowedDirs[filepath.Dir(targetBinPath)] || !safeComponent.MatchString(filepath.Base(targetBinPath)) {
		return "", fmt.Errorf("target binary path is outside executable directories: %q", targetBinPath)
	}
	fullTargetPath := filepath.Join(optDir, strings.TrimPrefix(targetBinPath, string(filepath.Separator)))

	script := fmt.Sprintf(`#!/bin/sh
# Generated by upm for foreign package %s (%s)
# Sandbox wrapper executing binary within isolated bubblewrap environment

TARGET_BIN=%s
OPT_DIR=%s

if [ ! -f "$TARGET_BIN" ]; then
	echo "upm: foreign binary not found: $TARGET_BIN" >&2
    exit 127
fi

BWRAP_BIN=$(command -v bwrap 2>/dev/null || echo "/usr/bin/bwrap")
if [ ! -x "$BWRAP_BIN" ]; then
	echo "upm: bubblewrap is required to execute foreign packages safely" >&2
    exit 127
fi

if [ -z "${HOME:-}" ] || [ ! -d "$HOME" ]; then
	echo "upm: a valid HOME is required to run foreign packages" >&2
	exit 127
fi

FOREIGN_LIB="$OPT_DIR/usr/lib:$OPT_DIR/usr/lib64:$OPT_DIR/lib:$OPT_DIR/lib64"
FOREIGN_PATH="$OPT_DIR/usr/bin:$OPT_DIR/bin:${PATH:-/usr/bin:/bin}"

exec "$BWRAP_BIN" \
	--die-with-parent \
	--new-session \
	--clearenv \
    --ro-bind / / \
    --ro-bind "$OPT_DIR" "$OPT_DIR" \
    --dev /dev \
    --proc /proc \
	--tmpfs /tmp \
	--bind "$HOME" "$HOME" \
	--setenv HOME "$HOME" \
	--setenv USER "${USER:-}" \
	--setenv LANG "${LANG:-C.UTF-8}" \
	--setenv LD_LIBRARY_PATH "$FOREIGN_LIB:${LD_LIBRARY_PATH:-}" \
    --setenv PATH "$FOREIGN_PATH" \
    "$TARGET_BIN" "$@"
`, pkgName, provider, shellQuote(fullTargetPath), shellQuote(optDir))

	return script, nil
}

func shellQuote(value string) string {
	return "'" + strings.ReplaceAll(value, "'", "'\"'\"'") + "'"
}

// CreateWrapperFile writes the generated wrapper script to destBinDir/binaryName with 0755 permissions.
func CreateWrapperFile(destBinDir, provider, pkgName, binaryName, targetBinPath string) (string, error) {
	script, err := GenerateBwrapWrapper(provider, pkgName, binaryName, targetBinPath)
	if err != nil {
		return "", err
	}

	if err := os.MkdirAll(destBinDir, 0755); err != nil {
		return "", fmt.Errorf("failed to create directory %s: %w", destBinDir, err)
	}

	wrapperPath := filepath.Join(destBinDir, binaryName)
	tempFile, err := os.CreateTemp(destBinDir, ".upm-wrapper-*")
	if err != nil {
		return "", fmt.Errorf("failed creating temporary wrapper: %w", err)
	}
	tempPath := tempFile.Name()
	defer os.Remove(tempPath)
	if _, err := tempFile.WriteString(script); err != nil {
		tempFile.Close()
		return "", fmt.Errorf("failed writing temporary wrapper: %w", err)
	}
	if err := tempFile.Chmod(0755); err != nil {
		tempFile.Close()
		return "", fmt.Errorf("failed setting wrapper permissions: %w", err)
	}
	if err := tempFile.Sync(); err != nil {
		tempFile.Close()
		return "", fmt.Errorf("failed syncing wrapper: %w", err)
	}
	if err := tempFile.Close(); err != nil {
		return "", fmt.Errorf("failed closing wrapper: %w", err)
	}
	if err := os.Link(tempPath, wrapperPath); err != nil {
		return "", fmt.Errorf("failed writing wrapper script %s: %w", wrapperPath, err)
	}

	return wrapperPath, nil
}
